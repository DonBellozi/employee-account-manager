from __future__ import annotations

from datetime import datetime, time


"""Единое окно плановых блокировок для всего проекта.

Все контуры, которые сами решают отключить учетную запись — AD, Zimbra и
Synology DSM — делают это в одно и то же время суток. Единое окно упрощает
разбор инцидентов: если утром обнаружилась лишняя блокировка, искать причину
нужно в одном интервале журнала, а не в трех разных расписаниях.

Ручная блокировка из раздела «Блокировка» сюда не относится: оператор
запускает ее осознанно и ждать вечера не должен.
"""

BLOCK_TIME = time(19, 10)
BLOCK_TIME_LABEL = "19:10"

# Недоступный сервер вечером — штатная ситуация. Повторяем попытку с ровным
# интервалом ограниченное число раз и переносим остаток на следующие сутки.
BLOCK_RETRY_MINUTES = 10
BLOCK_MAX_ATTEMPTS = 6


def is_block_window_open(now: datetime) -> bool:
    """Наступило ли время плановых блокировок в указанный местный момент."""
    return now.time().replace(tzinfo=None) >= BLOCK_TIME


def block_window_label() -> str:
    return (
        f"{BLOCK_TIME_LABEL}, повтор каждые {BLOCK_RETRY_MINUTES} мин "
        f"до {BLOCK_MAX_ATTEMPTS} попыток"
    )
